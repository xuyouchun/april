#! /usr/bin/python
"""Generates docs/diagnostics.md, the catalog of the diagnostics of the compiler, from the sources.

    python tools/gen_diagnostics.py            # writes docs/diagnostics.md
    python tools/gen_diagnostics.py --check    # fails when the file is not up to date, or a rule
                                               # of the codes or of the messages is broken

The code of a diagnostic is its number: AP + 4 digits. Nothing else tells a code, so the numbers
are written in the enums. The levels follow the ranges: AP1000 - AP1999 are informations,
AP4000 - AP4999 are warnings, the others are errors.
"""

import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

# The enums that have the codes: (the name of the enum, the header, the source of the messages).
ENUMS = [
    ('compile_log_code_t', 'include/modules/compile.h', 'modules/compile/compile.cpp'),
    ('common_log_code_t',  'modules/compile/__ast.h',    'modules/compile/ast.cpp'),
    ('compile_error_code_t', 'include/modules/core.h',   'modules/core/core.cpp'),
]

# The ranges of the codes.
RANGES = [
    (1,    999,  'syntax, lexical analysis and the compiler itself'),
    (1000, 1999, 'informations'),
    (2000, 2999, 'declarations: members, types, constructors, enums, operators, entry points'),
    (3000, 3999, 'names: definitions, lookup, assemblies'),
    (4000, 4999, 'warnings'),
    (5000, 5999, 'statements and expressions'),
    (6000, 6999, 'generics and constraints'),
]


def read(path):
    with open(os.path.join(ROOT, path), 'rb') as f:
        return f.read().decode('utf-8').replace('\r\n', '\n')


def level_of(code):
    if 1000 <= code < 2000:
        return 'info'
    if 4000 <= code < 5000:
        return 'warning'
    return 'error'


def enum_values(header, name):
    text = read(header)
    m = re.search(r'X_ENUM_?\(' + name + r'[^)]*\)(.*?)X_ENUM_END', text, re.S)
    assert m, 'enum %s is not found in %s' % (name, header)

    values = {}
    for item in re.finditer(r'^\s*(\w+)\s*=\s*(\d+)\s*,', m.group(1), re.M):
        if not item.group(1).startswith('__'):
            values[item.group(1)] = int(item.group(2))

    return values


def messages(source, name):
    text = read(source)
    m = re.search(r'X_ENUM_INFO\(' + name + r'\)(.*?)X_ENUM_INFO_END', text, re.S)
    assert m, 'the messages of %s are not found in %s' % (name, source)

    result = {}
    body = m.group(1)
    for item in re.finditer(r'X_D\((\w+),', body):
        # The strings, until the closing parenthesis of X_D.
        k = item.end()
        depth = 1
        pieces = []
        while depth > 0:
            c = body[k]
            if c == '"':
                end = k + 1
                while body[end] != '"':
                    end += 2 if body[end] == '\\' else 1
                pieces.append(body[k + 1:end])
                k = end
            elif c == '(':
                depth += 1
            elif c == ')':
                depth -= 1
            k += 1

        text = ''.join(pieces).replace('\\"', '"').replace('\\\\', '\\')
        result[item.group(1)] = text

    return result


def collect():
    """Returns [(code, name, message, enum)] sorted by code."""
    rows = []
    for enum, header, source in ENUMS:
        values = enum_values(header, enum)
        texts = messages(source, enum)

        for name, code in values.items():
            rows.append((code, name, texts.get(name), enum))

    rows.sort()
    return rows


def render(rows):
    lines = [
        '# Diagnostics',
        '',
        'This file is generated by `tools/gen_diagnostics.py` from the sources, do not edit it.',
        '',
        'The code of a diagnostic is its number: `AP` and 4 digits. A code is never changed, and',
        'never used for another message: a message that is not used any more keeps its number.',
        '',
        '## Ranges',
        '',
        '| Codes | Meaning |',
        '| --- | --- |',
    ]

    for lo, hi, text in RANGES:
        lines.append('| AP%04d - AP%04d | %s |' % (lo, hi, text))

    lines += [
        '',
        'The level follows the range: AP1000 - AP1999 are informations, AP4000 - AP4999 are warnings,',
        'the others are errors.',
        '',
        '## Style of the messages',
        '',
        '- The message begins in lower case, and has no period at the end.',
        '- The names of the things (types, members, variables, keywords, operators, tokens) are in',
        '  double quotes: `type "Foo" is not defined`.',
        '- The problem is said as it is: `"x" is not defined`, `"x" is already defined`, `cannot ...`.',
        '- What is missing is said as `expected X` (syntax) or `X is missing` (a part of a declaration).',
        '- The position of an error is that of the code that is wrong: the unexpected token, or the',
        '  end of the code before the missing one.',
        '- An error that is only the consequence of another one is not told.',
        '',
        '## Catalog',
        '',
        '| Code | Level | Name | Message |',
        '| --- | --- | --- | --- |',
    ]

    for code, name, message, enum in rows:
        text = (message or '').replace('|', '\\|')
        lines.append('| AP%04d | %s | `%s` | %s |' % (code, level_of(code), name, text))

    return '\n'.join(lines) + '\n'


def problems(rows):
    """Returns the rules that are broken."""
    found = []

    seen = {}
    for code, name, message, enum in rows:
        if code in seen:
            found.append('code AP%04d is used by %s and %s' % (code, seen[code], name))
        seen[code] = name

        if not 1 <= code <= 9999:
            found.append('code %d of %s is out of range' % (code, name))

        if message is None:
            found.append('%s (AP%04d) has no message' % (name, code))
            continue

        if message == '%1%':
            continue    # the message is told by the caller.

        if message[:1].isalpha() and message[:1].isupper():
            found.append('%s: the message begins in upper case: %s' % (name, message))

        if message.endswith('.'):
            found.append('%s: the message ends with a period: %s' % (name, message))

        if "'" in message:
            found.append('%s: use double quotes for the names: %s' % (name, message))

        for word in ('undetermind', 'defination', 'redundance', 'implemenation', 'beging'):
            if word in message:
                found.append('%s: misspelled "%s": %s' % (name, word, message))

        if message.count('"') % 2:
            found.append('%s: the quotes do not match: %s' % (name, message))

    return found


def main():
    rows = collect()
    text = render(rows)
    path = os.path.join(ROOT, 'docs', 'diagnostics.md')

    if '--check' in sys.argv:
        broken = problems(rows)

        current = open(path, 'rb').read().decode('utf-8').replace('\r\n', '\n') \
            if os.path.exists(path) else ''
        if current != text:
            broken.append('docs/diagnostics.md is not up to date: run tools/gen_diagnostics.py')

        for line in broken:
            print(line)

        return 1 if broken else 0

    with open(path, 'wb') as f:
        f.write(text.encode('utf-8'))

    print('written %s, %d diagnostics' % (path, len(rows)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
